//! S2-palette-parse: the palette is parsed from wallust `colors.sh`.
//!
//! Fixtures mirror the real wallust template: a header comment, `wallpaper=`, `background=`,
//! `foreground=`, `cursor=`, a blank line, then `color0=`..`color15=`, all single-quoted.

use ln_hub::{Palette, PaletteError};
use ratatui::style::Color;

/// (name, hex as written in the file, expected rgb). Hand-derived literals; mixed hex case
/// because real wallust output is upper-case while the spec example is lower-case.
const COLORS: [(&str, &str, (u8, u8, u8)); 16] = [
    ("color0", "#1F0C00", (0x1f, 0x0c, 0x00)),
    ("color1", "#874C2D", (0x87, 0x4c, 0x2d)),
    ("color2", "#945D3C", (0x94, 0x5d, 0x3c)),
    ("color3", "#A26F4C", (0xa2, 0x6f, 0x4c)),
    ("color4", "#aabbcc", (0xaa, 0xbb, 0xcc)),
    ("color5", "#BE926B", (0xbe, 0x92, 0x6b)),
    ("color6", "#BE926C", (0xbe, 0x92, 0x6c)),
    ("color7", "#F5D9BE", (0xf5, 0xd9, 0xbe)),
    ("color8", "#AC9885", (0xac, 0x98, 0x85)),
    ("color9", "#B4653C", (0xb4, 0x65, 0x3c)),
    ("color10", "#C67D50", (0xc6, 0x7d, 0x50)),
    ("color11", "#d89465", (0xd8, 0x94, 0x65)),
    ("color12", "#EBAC7A", (0xeb, 0xac, 0x7a)),
    ("color13", "#FDC38F", (0xfd, 0xc3, 0x8f)),
    ("color14", "#FDC390", (0xfd, 0xc3, 0x90)),
    ("color15", "#F5D9BF", (0xf5, 0xd9, 0xbf)),
];

/// Full wallust-style file; `skip` drops the line for that key, `override_line` replaces
/// the line for a key with the given value text.
fn colors_sh(skip: Option<&str>, override_line: Option<(&str, &str)>) -> String {
    let mut out = String::new();
    out.push_str("# Shell variables generated by wallust\n");
    out.push_str("wallpaper='/home/ln/Pictures/Wallpapers/cat.jpg'\n");
    let head = [
        ("background", "#170000"),
        ("foreground", "#e0d0c0"),
        ("cursor", "#E2B394"),
    ];
    let push = |out: &mut String, k: &str, v: &str| {
        if skip == Some(k) {
            return;
        }
        let v = match override_line {
            Some((ok, ov)) if ok == k => ov,
            _ => v,
        };
        out.push_str(&format!("{k}='{v}'\n"));
    };
    for (k, v) in head {
        push(&mut out, k, v);
    }
    out.push('\n');
    for (k, v, _) in COLORS {
        push(&mut out, k, v);
    }
    out
}

fn is_missing(e: &PaletteError, key: &str) -> bool {
    matches!(e, PaletteError::Missing(k) if &**k == key)
}

fn is_invalid(e: &PaletteError, key: &str) -> bool {
    matches!(e, PaletteError::Invalid(k) if &**k == key)
}

// Breaks if: hex is not decoded per channel (or case-insensitively), colors are mapped to the
// wrong names, or unknown names do not yield None.
#[test]
fn full_input_resolves_every_named_color() {
    let p = Palette::parse_colors_sh(&colors_sh(None, None)).expect("full palette parses");
    assert_eq!(p.get("color4"), Some(Color::Rgb(0xaa, 0xbb, 0xcc)));
    assert_eq!(p.get("background"), Some(Color::Rgb(0x17, 0x00, 0x00)));
    assert_eq!(p.get("foreground"), Some(Color::Rgb(0xe0, 0xd0, 0xc0)));
    for (name, _, (r, g, b)) in COLORS {
        assert_eq!(p.get(name), Some(Color::Rgb(r, g, b)), "{name}");
    }
    assert_eq!(p.get("color99"), None);
    assert_eq!(p.get("cursor"), None);
}

// Breaks if: a palette missing a required key is accepted (or the wrong key is reported).
#[test]
fn missing_color4_is_reported_by_name() {
    let err = Palette::parse_colors_sh(&colors_sh(Some("color4"), None))
        .err()
        .expect("missing color4 must be an error");
    assert!(is_missing(&err, "color4"), "got {err:?}");
}

// Breaks if: a non-hex value is accepted, mapped to a default, or reported as Missing.
#[test]
fn non_hex_color4_is_invalid() {
    let err = Palette::parse_colors_sh(&colors_sh(None, Some(("color4", "zzz"))))
        .err()
        .expect("color4='zzz' must be an error");
    assert!(is_invalid(&err, "color4"), "got {err:?}");
}

// Breaks if: comments, `wallpaper=` (path with spaces and `=`), blank lines
// or other unknown assignments make the parser error out or corrupt values.
#[test]
fn comments_wallpaper_and_blank_lines_are_ignored() {
    let mut s = String::from("# a leading comment\n\n   # indented comment\n");
    s.push_str("wallpaper='/tmp/a b/x=y.jpg'\n\n");
    s.push_str(&colors_sh(None, None));
    s.push_str("# trailing comment\n\nwallpaper='/another.png'\n");
    let p = Palette::parse_colors_sh(&s).expect("extras are ignored");
    assert_eq!(p.get("color4"), Some(Color::Rgb(0xaa, 0xbb, 0xcc)));
    assert_eq!(p.get("background"), Some(Color::Rgb(0x17, 0x00, 0x00)));
    assert_eq!(p.get("color15"), Some(Color::Rgb(0xf5, 0xd9, 0xbf)));
    assert_eq!(p.get("wallpaper"), None);
}
